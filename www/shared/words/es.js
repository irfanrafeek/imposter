// ============================================================
// THE SPANISH WORD CATALOGUE
// ============================================================
// Written, not translated from en.js. Parity with the English catalogue is
// explicitly not a goal: a category that does not land at a Spanish-speaking
// table is worth less than a shorter one that does.
//
// NEUTRAL SPANISH, FOR SPANISH SPEAKERS EVERYWHERE. This was first written
// for Spain and had to be redone (#139), and the reason matters, because it
// is not the reason the interface was redone. In UI copy a Spain-ism is a
// wrong tone. HERE IT IS A DEAD ROUND: everyone at the table sees the same
// secret word and has to give a clue for it, so a word half of them do not
// know stops the game rather than colouring it. If a player in Bogota draws
// `Fregona`, nobody can say anything.
//
// Two different failures, and the second is the sneaky one:
//
//   THE THING ONLY EXISTS IN SPAIN.  Fabada, Salmorejo, Migas, Chiringuito,
//   Trastero, Torrijas. Obvious once you look, and all of them are gone.
//
//   THE THING IS UNIVERSAL BUT THE WORD IS NOT.  This is the one that reads
//   fine and still breaks. Ordenador/computadora, nevera/refrigerador,
//   gafas/lentes, patatas/papas, zumo/jugo, judias/frijoles, piso/
//   departamento, melocoton/durazno, boligrafo/marcador. Where a word splits,
//   this file takes the form the most speakers use, and where it splits three
//   ways with no majority (fregona, altavoz, cremallera) it picks a different
//   object entirely rather than pretending one form wins.
//
// Two traps that are not vocabulary at all:
//   `Tortilla` is an omelette in Spain and a flatbread in Mexico, so the
//   table gives clues for two different foods and accuses the honest players.
//   Gone, for that reason and no other.
//   `Chaqueta` is an ordinary jacket in Spain and vulgar slang in Mexico.
//
// Cine y TV and Futbol were rebuilt rather than patched. Eighteen of the
// first twenty shows were Spanish television, and all eight clubs were
// LaLiga with nothing from the Americas.
//
// Regional catalogues (es-MX, es-AR) stay possible: loadCatalog() already
// resolves them, and this file is the neutral default they would sit beside,
// not a thing they would have to replace.
//
// The KEYS below stay English. They are data keys with history behind them,
// not labels; see the header of index.js. Only the arrays are Spanish.
//
// This file is the shelf. #137 fills it, one category at a time so each can
// be read through before the next is written. Until a category has words,
// scripts/check-words.mjs reports it as not-yet-written rather than failing,
// and loadCatalog() falls back to English while the whole file is empty, so
// a half-finished catalogue can never deal `undefined` as the secret word.
//
// Two Spanish-only traps, neither of which a checker can see:
//
//   - GENDER LEAKS THE ANSWER. `Roja` next to a hidden noun says the noun is
//     feminine, which cuts the field in half before anyone speaks. Prefer
//     hints that do not inflect: a noun-ish adjective, or one whose masculine
//     and feminine forms are identical (`Grande`, `Verde`, `Brillante`).
//
//   - THE ARTICLE IS PART OF THE WORD, or it is not, but it has to be one or
//     the other everywhere. `Playa` and `La Playa` in the same catalogue read
//     as two different registers on the card. No articles is the rule here.
//
// AND ONE RULE ABOUT WHAT A HINT SHOULD BE, learned the hard way on Food.
//
// English hints are overwhelmingly PHYSICAL: what the thing looks, feels or
// tastes like. Cheesy, Stacked, Round, Melted, Glazed. Occasion words like
// Morning or Festive appear as the second hint, not as both.
//
// The gender rule above pushes hard the other way. Spanish sensory adjectives
// nearly all inflect (cremoso/a, salado/a, redondo/a, blando/a), so avoiding
// the leak drives you off adjectives and onto nouns, and nouns about food and
// animals skew towards occasions and places. The first draft of Food came out
// a third context hints against English's fifth, and entries like
// `Paella: Domingo / Compartir` were close to unguessable.
//
// The way out is physical NOUNS, which are concrete AND gender-safe:
//   texture and part   Corteza, Espuma, Grano, Hueso, Capas, Pulpa, Lámina
//   shape              Rodaja, Curva, Punta, Espiral, Franjas
//   body               Colmillo, Trompa, Aleta, Púas, Cresta, Caparazón
//   sound and movement Ladrido, Rugido, Aleteo, Galope, Croar
// plus the invariant sensory adjectives Spanish does have: Crujiente, Suave,
// Dulce, Caliente, Picante, Brillante, Fuerte, Veloz, Feroz, Frágil.
//
// AND THE ESCAPE HATCH THAT KEEPS IT SOUNDING HUMAN. The obvious way to
// avoid `blando` or `largo` is to reach for `blandura` or `largura`, and
// that is a trap: those forms are gender-safe but bookish, and a page full
// of them is exactly what reads as machine-translated. Nobody says
// `cremosidad`.
//
// Two invariant forms that are also idiomatic:
//   INFINITIVE VERBS   Untar, Refrescar, Sorber, Planchar, Fregar, Apoyar,
//                      Limpiar, Serpentear. Never inflect, always natural.
//   CONCRETE NOUNS     Grano, Corteza, Espuma, Cuello, Bandada.
//
// Abstract nouns are fine when they are the word a person would actually
// reach for: Velocidad, Elegancia, Torpeza, Serenidad. The test is whether
// you would say it out loud, not whether it is grammatical.
//
// So: EVERY ENTRY GETS AT LEAST ONE PHYSICAL HINT. The second may be an
// occasion, and often should be, because the impostor sees only one at random
// and that variance is what makes a round tense rather than solvable.
//
// A hint must also not NAME the thing. Regional origin is the trap here:
// `Valencia` on Paella or `Burgos` on Morcilla identifies the dish outright,
// and since only the impostor sees the hint, an identifying one hands them
// something safe to say and makes them impossible to catch.

